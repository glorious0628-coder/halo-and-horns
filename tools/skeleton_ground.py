"""Studio part skeleton of the Halo v2 walking ground (이미지 생성 1, 2026-10-11, SPEC A23-120/121 stage 4): roads, plaza circles,
yards, stairs, rails. Same method as tools/skeleton_civic.py: Python writes ONE WorldKit Luau script (build/skeleton_ground.luau),
tools/worldkit/skeleton_ground_run.py runs it with studio_mcp execute_luau (Edit mode, WorldKit only).

  py tools/skeleton_ground.py [--only roads,plaza,yards,stairs,rails,bridges] [--offset X,Z] [--out build/skeleton_ground.luau]

Reads docs/design/halo_plan_v2_2026-10-11.json: roads (id, w, grade, pts), yards, water.pools id "fountain", bridges (count only).
The Luau measures the ground on the Terrain (workspace:Raycast down on Terrain only, IgnoreWater) and lays Parts on it:
  * Workspace.HaloV2.Ground (Folder, rebuilt on every full run) with Roads / Plaza / Yards / Stairs / Rails;
  * every walking part carries the CollectionService tag "WalkGround" (Config.Ground.Tag): road plates, stepping stones, plaza
    discs, yard discs, stairs, landings, and the Workspace.HaloV2.Bridges Bridge_* decks. Rails and gold trim are NOT ground;
  * materials as skeleton_civic.py: marble = Marble + MaterialVariant HH_HaloMarbleBlock_Cream + (255,244,222), gold = Metal +
    HH_HaloGoldTrim + (255,168,36), cobble = Cobblestone (214,200,168), stepping stone = Slate (210,205,195);
  * grade 1 = marble plates + two gold lines, grade 2 = cobblestone plates, grade 3 = stepping stones (deterministic jitter from the
    id's letter codes); a bend > 8 deg gets an upright disc of diameter w; a 5-stud step steeper than 24 deg becomes real stairs
    (rise 0.5, tread 1.2) with a landing at each end and rails on both sides;
  * the spawn passage (|x| <= 12, z -330..-432) gets the main road only; the plaza discs (fountain r 40, spawn r 14) get a
    CSG gold ring (SubtractAsync, pcall, fallback = 48 small gold boxes) and the fountain disc rails where the land outside is
    >= 1.5 lower; at most 4000 parts (the point spacing grows when the estimate is higher).
--only picks stages: roads (plates, stones, bend discs, gold lines), plaza (discs + rings), yards, stairs (steps + landings),
rails (stair rails + plaza edge rails), bridges (tags + bridge rails). A partial run rebuilds only those stages' parts
(attribute Stage); a full run rebuilds the whole Ground folder.
"""
