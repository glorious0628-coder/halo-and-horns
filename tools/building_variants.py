"""Studio Luau that makes / updates the building tile MaterialVariants (이미지 개발 2026-10-11, A23-120: Halo town
buildings = part skeleton + tile MaterialVariant + Tripo trim parts).

  py tools/building_variants.py [art/models/worldkit/building_variants_halo.json] [--out build/building_variants.luau]
                                [--only HH_Fabric[,HH_...]]   # a Luau that makes / updates just those variants
The Luau creates each MaterialVariant in MaterialService by Name (or updates the one that is there: maps, base
material, StudsPerTile, pattern), never overrides a base material, and lists the parts that already use it. ALLOW_MAIN
is false: the main place refuses it until 메인 반영 1 sets it (practice Studios: WorldKit, UiSandbox).
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LUAU = r'''-- building_variants (generated by tools/building_variants.py from %(src)s). 이미지 개발 2026-10-11.
local ALLOW_MAIN = false -- 메인 반영 1: true only for the main place, after the practice Studio check
if (game.PlaceId == 81671223175574 or string.find(game.Name, "GoodEvil")) and not ALLOW_MAIN then
	error("WRONG STUDIO: main (ALLOW_MAIN is false)")
end
local MS = game:GetService("MaterialService")
local LIST = %(list)s
local out = {}
for _, v in LIST do
	local mv = MS:FindFirstChild(v.name)
	local made = false
	if not (mv and mv:IsA("MaterialVariant")) then
		mv = Instance.new("MaterialVariant")
		mv.Name = v.name
		made = true
	end
	mv.BaseMaterial = Enum.Material[v.base]
	mv.ColorMap = v.color
	mv.NormalMap = v.normal or ""
	mv.RoughnessMap = v.rough or ""
	mv.MetalnessMap = v.metal or ""
	mv.StudsPerTile = v.studs
	mv.MaterialPattern = Enum.MaterialPattern[v.pattern]
	mv.Parent = MS
	local used = 0
	for _, d in workspace:GetDescendants() do
		if d:IsA("BasePart") and d.MaterialVariant == v.name then used += 1 end
	end
	table.insert(out, string.format("%%s %%s: base %%s, %%g studs/tile, %%s, parts using it %%d", made and "MADE" or "UPDATED",
		v.name, v.base, v.studs, v.pattern, used))
end
return table.concat(out, "\n")
'''


def q(s):
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("src", nargs="?", default=os.path.join(ROOT, "art", "models", "worldkit", "building_variants_halo.json"))
    ap.add_argument("--out", default=os.path.join(ROOT, "build", "building_variants.luau"))
    ap.add_argument("--only", default="", help="comma-separated variant names; the rest are left alone (main place: smallest change)")
    a = ap.parse_args()
    with open(a.src, encoding="utf-8") as f:
        data = json.load(f)
    rows = []
    only = {x.strip() for x in a.only.split(",") if x.strip()}
    if only and not only <= {v["name"] for v in data["variants"]}:
        raise SystemExit("unknown variant in --only: " + ", ".join(sorted(only - {v["name"] for v in data["variants"]})))
    for v in data["variants"]:
        if only and v["name"] not in only:
            continue
        fields = [f"name = {q(v['name'])}", f"base = {q(v['base'])}", f"studs = {float(v['studsPerTile'])}",
                  f"pattern = {q(v.get('pattern', 'Regular'))}", f"color = {q(v['color'])}"]
        fields += [f"{k} = {q(v[k])}" for k in ("normal", "rough", "metal") if v.get(k)]
        rows.append("\t{ " + ", ".join(fields) + " },\n")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    with open(a.out, "w", encoding="utf-8", newline="\n") as f:
        f.write(LUAU % {"src": os.path.relpath(a.src, ROOT).replace("\\", "/"), "list": "{\n" + "".join(rows) + "}"})
    print(a.out, len(rows), "variants")


if __name__ == "__main__":
    main()
