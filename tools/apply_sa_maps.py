"""Write the Studio Luau that puts the uploaded 4-map SurfaceAppearances on the game's MeshParts ("maps" mode of
tools/zone_split_batch.py; 이미지 개발 2026-10-10, A23-107).

  py tools/apply_sa_maps.py <zone> [--mode survey|apply] [--out build/apply_sa_<zone>.luau]

Input: art/models/worldkit/sa_maps_<zone>_2026-10-10.json — {"items": [{"name", "meshId", "match": {"tex"|"color": id},
"sa": {"color", "normal", "metal", "rough"}}]} (ids from the uploads; meshId / match from the import records).
A MeshPart is changed only when its MeshId AND its current look match the record: "tex" = MeshPart.TextureID, "color" =
the ColorMap of its SurfaceAppearance. Same mesh with another texture (e.g. the meadow copies Kit_X_*_M_tex, the
blue/green stalls on the red stall's mesh) is listed as "skipped (other look)" and left alone. survey = list only.
Run with execute_luau in Edit mode (plugin security sets SurfaceAppearance maps). The script refuses the main place
unless ALLOW_MAIN is set to true in the generated file (메인 반영 1 sets it after the UiSandbox run is checked).
"""
import argparse
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LUAU = r'''-- apply_sa_maps (generated by tools/apply_sa_maps.py, zone %(zone)s, mode %(mode)s). 이미지 개발 2026-10-10.
local ALLOW_MAIN = false -- 메인 반영 1: set true only for the main place after the UiSandbox run was checked
if (game.PlaceId == 81671223175574 or string.find(game.Name, "GoodEvil")) and not ALLOW_MAIN then
	error("WRONG STUDIO: main (ALLOW_MAIN is false)")
end
local MODE = "%(mode)s"
local ITEMS = %(items)s
local byMesh = {}
for _, it in ITEMS do
	byMesh[it.meshId] = byMesh[it.meshId] or {}
	table.insert(byMesh[it.meshId], it)
end
local function idOf(s)
	return string.match(tostring(s or ""), "%%d+") or ""
end
local function look(mp)
	local sa = mp:FindFirstChildOfClass("SurfaceAppearance")
	return idOf(mp.TextureID), sa and idOf(sa.ColorMap) or ""
end
local changed, already, skipped, failed = {}, {}, {}, {}
local roots = { workspace, game:GetService("ServerStorage"), game:GetService("ReplicatedStorage") }
for _, root in roots do
	for _, mp in root:GetDescendants() do
		if not mp:IsA("MeshPart") then
			continue
		end
		local list = byMesh[idOf(mp.MeshId)]
		if not list then
			continue
		end
		local tex, col = look(mp)
		local hit
		for _, it in list do
			if (it.match.tex and it.match.tex == tex) or (it.match.color and (it.match.color == col or idOf(it.sa.color) == col)) then
				hit = it
				break
			end
		end
		local row = string.format("%%s  size %%.2f x %%.2f x %%.2f  tex %%s  sa %%s", mp:GetFullName(), mp.Size.X, mp.Size.Y, mp.Size.Z, tex, col)
		if not hit then
			table.insert(skipped, row)
			continue
		end
		if col == idOf(hit.sa.color) then
			table.insert(already, hit.name .. "  " .. row)
			continue
		end
		if MODE == "apply" then
			local ok, err = pcall(function()
				local sa = Instance.new("SurfaceAppearance")
				sa.Name = "SurfaceAppearance"
				sa.ColorMap = hit.sa.color
				if hit.sa.normal then sa.NormalMap = hit.sa.normal end
				if hit.sa.metal then sa.MetalnessMap = hit.sa.metal end
				if hit.sa.rough then sa.RoughnessMap = hit.sa.rough end
				local old = mp:FindFirstChildOfClass("SurfaceAppearance")
				sa.Parent = mp
				if old then old:Destroy() end
			end)
			if not ok then
				table.insert(failed, hit.name .. "  " .. row .. "  " .. tostring(err))
				continue
			end
		end
		table.insert(changed, hit.name .. "  " .. row)
	end
end
local out = { string.format("%%s: %%s %%d, already %%d, skipped (same mesh, other look) %%d, failed %%d", MODE,
	MODE == "apply" and "changed" or "would change", #changed, #already, #skipped, #failed) }
for _, t in { { "CHANGE", changed }, { "ALREADY", already }, { "SKIP", skipped }, { "FAIL", failed } } do
	for _, r in t[2] do
		table.insert(out, t[1] .. "  " .. r)
	end
end
return table.concat(out, "\n")
'''


def luau_value(v, indent="\t"):
    if isinstance(v, dict):
        inner = ", ".join(f"{k} = {luau_value(x)}" for k, x in v.items())
        return "{ " + inner + " }"
    if isinstance(v, list):
        return "{\n" + "".join(f"{indent}{luau_value(x)},\n" for x in v) + "}"
    if isinstance(v, (int, float)):
        return repr(v)
    return json.dumps(str(v))


def latest_records():
    """name -> the newest import record (art/models/worldkit/import*_assets_*.json, file names sort by date)."""
    import glob
    out = {}
    files = sorted(glob.glob(os.path.join(ROOT, "art", "models", "worldkit", "import*_assets_*.json")),
                   key=lambda p: os.path.basename(p).rsplit("_", 1)[-1])
    for p in files:
        try:
            with open(p, encoding="utf-8") as f:
                d = json.load(f)
        except (OSError, ValueError):
            continue
        for it in (d.get("items") if isinstance(d, dict) else d) or []:
            if isinstance(it, dict) and it.get("name") and it.get("meshId"):
                out[it["name"]] = dict(it, _file=os.path.basename(p))
    return out


def collect(zone):
    """sa_maps_<zone> json from the batch report (maps-mode models), the import records (meshId, today's look) and the
    uploaded ids in art/ui/asset_ids.json (keys SA_<name>_C / _N / _M / _R)."""
    rep = os.path.join(ROOT, "art", "models", "tripo", f"split_{zone}", "split_report.json")
    with open(rep, encoding="utf-8") as f:
        report = json.load(f)
    with open(os.path.join(ROOT, "art", "ui", "asset_ids.json"), encoding="utf-8") as f:
        ids = json.load(f)
    recs = latest_records()
    items, missing = [], []
    keys = {"C": "color", "N": "normal", "M": "metal", "R": "rough"}
    for name, r in report.items():
        if r.get("mode") != "maps":
            continue
        rec = recs.get(name)
        sa = {keys[t]: ids[f"SA_{name}_{t}"] for t in "CNMR" if f"SA_{name}_{t}" in ids}
        # decision (a), 이미지 생성 1 + 검수 10/10: no new colour map (a new one greys the SA while it waits for moderation) -
        # the colour stays the game's own (its SurfaceAppearance ColorMap, else the MeshPart TextureID)
        if rec and "color" not in sa and "normal" in sa:
            own = (rec.get("sa") or {}).get("color") or rec.get("textureId")
            if own:
                sa["color"] = own
        if not rec or "color" not in sa:
            missing.append(name + (" (no import record)" if not rec else " (not uploaded)"))
            continue
        if rec.get("sa") and rec["sa"].get("color"):
            match = {"color": rec["sa"]["color"]}
        else:
            match = {"tex": rec.get("textureId", "")}
        items.append({"name": name, "meshId": rec["meshId"], "match": match, "sa": sa, "record": rec["_file"]})
    out = os.path.join(ROOT, "art", "models", "worldkit", f"sa_maps_{zone}_2026-10-10.json")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        json.dump({"note": f"이미지 개발 2026-10-10 A23-107 maps mode ({zone}): four new 1024 SurfaceAppearance maps per model on "
                   "the game's own MeshPart (same UV). tools/apply_sa_maps.py writes the Studio Luau.", "items": items},
                  f, ensure_ascii=False, indent=1)
    print(out, len(items), "items; missing:", missing)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("zone")
    ap.add_argument("--mode", default="survey", choices=["survey", "apply"])
    ap.add_argument("--collect", action="store_true", help="build the sa_maps json from the report, records and ids")
    ap.add_argument("--out")
    a = ap.parse_args()
    if a.collect:
        collect(a.zone)
        return
    src = os.path.join(ROOT, "art", "models", "worldkit", f"sa_maps_{a.zone}_2026-10-10.json")
    with open(src, encoding="utf-8") as f:
        data = json.load(f)
    items = []
    for it in data["items"]:
        match = {k: str(v).split("//")[-1] for k, v in it["match"].items()}
        items.append({"name": it["name"], "meshId": str(it["meshId"]).split("//")[-1], "match": match, "sa": it["sa"]})
    code = LUAU % {"zone": a.zone, "mode": a.mode, "items": luau_value(items)}
    out = a.out or os.path.join(ROOT, "build", f"apply_sa_{a.zone}_{a.mode}.luau")
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(code)
    print(out, len(items), "items")


if __name__ == "__main__":
    main()
