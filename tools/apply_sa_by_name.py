"""SurfaceAppearance by MeshPart NAME for new imports (이미지 개발 2026-10-10, for 이미지 생성 3's Halo town houses:
art/models/tripo/halo_houses/<house>/<part>_C/_N/_M/_R.png, part name = MeshPart name, e.g. HaloDomeHouse_02_Door).

  py tools/upload_sa_maps.py art/models/tripo/halo_houses/<house> --tags CNMR    (first: ids -> asset_ids SA_<part>_<T>)
  py tools/apply_sa_by_name.py <folder> [<folder> ...] [--mode survey|apply] [--out build/apply_sa_byname_<mode>.luau]

Writes a Studio Luau that walks workspace / ServerStorage / ReplicatedStorage and, for every MeshPart whose Name is one
of the parts (or whose parent's Name is, after a GLB import), puts a new SurfaceAppearance (ColorMap + NormalMap + MetalnessMap + RoughnessMap; AlphaMode Overlay) in
place of any old one. Parts named *_Glass get no maps: Material Glass, Transparency 0.45, Reflectance 0.25 (이미지
생성 3). Survey only counts. ALLOW_MAIN is false: the main place refuses it until 메인 반영 1 sets it after a practice
Studio run. Parts with no uploaded colour map are listed and left out.
"""
import argparse
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
GLASS = {"Transparency": 0.45, "Reflectance": 0.25}

LUAU = r'''-- apply_sa_by_name (generated by tools/apply_sa_by_name.py, mode %(mode)s). 이미지 개발 2026-10-10.
local ALLOW_MAIN = false -- 메인 반영 1: set true only for the main place after the practice Studio run was checked
if (game.PlaceId == 81671223175574 or string.find(game.Name, "GoodEvil")) and not ALLOW_MAIN then
	error("WRONG STUDIO: main (ALLOW_MAIN is false)")
end
local MODE = "%(mode)s"
local PARTS = %(parts)s
local GLASS = %(glass)s
local function idOf(s)
	return string.match(tostring(s or ""), "%%d+") or ""
end
local changed, already, failed, seen = {}, {}, {}, {}
for _, root in { workspace, game:GetService("ServerStorage"), game:GetService("ReplicatedStorage") } do
	for _, mp in root:GetDescendants() do
		if not mp:IsA("MeshPart") then
			continue
		end
		-- the part name is the MeshPart's, or its parent's (Studio's GLB import names a lone mesh 'Mesh_0' and keeps the
		-- part name on the Model / node above it, 이미지 생성 1 10/10)
		local key = mp.Name
		if not (PARTS[key] or GLASS[key]) and mp.Parent then key = mp.Parent.Name end
		local glass = GLASS[key]
		local it = PARTS[key]
		if not (it or glass) then
			continue
		end
		seen[key] = (seen[key] or 0) + 1
		if glass then
			if mp.Material == Enum.Material.Glass and math.abs(mp.Transparency - glass.Transparency) < 0.01 then
				table.insert(already, mp:GetFullName())
			else
				if MODE == "apply" then
					mp.Material = Enum.Material.Glass
					mp.Transparency = glass.Transparency
					mp.Reflectance = glass.Reflectance
					local old = mp:FindFirstChildOfClass("SurfaceAppearance")
					if old then old:Destroy() end
				end
				table.insert(changed, mp:GetFullName() .. "  (glass)")
			end
			continue
		end
		local sa0 = mp:FindFirstChildOfClass("SurfaceAppearance")
		if sa0 and idOf(sa0.ColorMap) == idOf(it.color) and idOf(sa0.NormalMap) == idOf(it.normal or "") then
			table.insert(already, mp:GetFullName())
			continue
		end
		if MODE == "apply" then
			local ok, err = pcall(function()
				local sa = Instance.new("SurfaceAppearance")
				sa.AlphaMode = Enum.AlphaMode.Overlay
				sa.ColorMap = it.color
				if it.normal then sa.NormalMap = it.normal end
				if it.metal then sa.MetalnessMap = it.metal end
				if it.rough then sa.RoughnessMap = it.rough end
				sa.Parent = mp
				if sa0 then sa0:Destroy() end
			end)
			if not ok then
				table.insert(failed, mp:GetFullName() .. "  " .. tostring(err))
				continue
			end
		end
		table.insert(changed, mp:GetFullName())
	end
end
local missing = {}
for name in PARTS do
	if not seen[name] then table.insert(missing, name) end
end
for name in GLASS do
	if not seen[name] then table.insert(missing, name .. " (glass)") end
end
table.sort(missing)
local out = { string.format("%%s: %%s %%d, already %%d, failed %%d, parts not found in this place %%d", MODE,
	MODE == "apply" and "changed" or "would change", #changed, #already, #failed, #missing) }
for _, t in { { "CHANGE", changed }, { "ALREADY", already }, { "FAIL", failed }, { "NOT FOUND", missing } } do
	for _, r in t[2] do
		table.insert(out, t[1] .. "  " .. r)
	end
end
return table.concat(out, "\n")
'''


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("folders", nargs="+")
    ap.add_argument("--mode", choices=("survey", "apply"), default="survey")
    ap.add_argument("--out")
    ap.add_argument("--glass", default="", help="extra glass part names (comma list) besides *_Glass")
    ap.add_argument("--ids", default=os.path.join(ROOT, "art", "ui", "asset_ids.json"), help="id record (tests)")
    a = ap.parse_args()
    with open(a.ids, encoding="utf-8") as f:
        ids = json.load(f)
    keys = {"C": "color", "N": "normal", "M": "metal", "R": "rough"}
    parts, glass, missing = {}, set(x for x in a.glass.split(",") if x), []
    for folder in a.folders:
        folder = os.path.abspath(folder)
        names = set()
        for p in glob.glob(os.path.join(folder, "*_[CNMR].png")):
            names.add(os.path.basename(p)[:-6])
        for n in sorted(names):
            if n.endswith("_Glass"):
                glass.add(n)
                continue
            sa = {keys[t]: ids[f"SA_{n}_{t}"] for t in "CNMR" if f"SA_{n}_{t}" in ids}
            if "color" not in sa:
                missing.append(n)
                continue
            parts[n] = sa
        for p in glob.glob(os.path.join(folder, "*_Glass*")):  # a glass part may have no maps at all
            b = os.path.basename(p).split(".")[0]
            if b.endswith("_Glass"):
                glass.add(b)
    plua = "{\n" + "".join(
        f"\t[{lua_str(n)}] = {{ " + ", ".join(f"{k} = {lua_str(v)}" for k, v in sa.items()) + " },\n"
        for n, sa in sorted(parts.items())) + "}"
    glua = "{\n" + "".join(
        f"\t[{lua_str(n)}] = {{ Transparency = {GLASS['Transparency']}, Reflectance = {GLASS['Reflectance']} }},\n"
        for n in sorted(glass)) + "}"
    out = a.out or os.path.join(ROOT, "build", f"apply_sa_byname_{a.mode}.luau")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    with open(out, "w", encoding="utf-8", newline="\n") as f:
        f.write(LUAU % {"mode": a.mode, "parts": plua, "glass": glua})
    print(out, len(parts), "parts,", len(glass), "glass; not uploaded:", missing)


if __name__ == "__main__":
    main()
