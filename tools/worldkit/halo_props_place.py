"""halo_props_place.py (이미지 생성 1, 2026-10-11): put the stage-5 props of the Halo v2 plan into WorldKit (Edit, no window).

Reads docs/design/halo_plan_v2_2026-10-11.json dressing.props (tools/halo_props_v2.py) and builds Workspace.HaloV2.Props:
  * StandIn  - kits whose approved model is not in Studio yet but an OLD WorldKit3D kit of the same kind is
               (Lantern, Planter, PotFlowers/FlowerPotHQ, RoundTree, Topiary, Balustrade) + the real Town_Halo_Fountain3.
               Clone scaled to the kit height x the prop scale; attribute StandIn = old kit name (layout check only:
               the old kits are not the final look, A23-96).
  * Placeholder - everything else (HaloReasonHQ_*, Flagpole, NEW_* kits): a half-transparent box of the kit size + a name
               label (blue = kit made but not imported, orange = NEW kit still to make).
Every object: attributes PropId, Kit, Why, Anchor; feet on the ground (ray down onto Terrain + HaloV2.Ground, tower-top
props onto HaloV2.Buildings). Re-running replaces the folder.
usage: py tools/worldkit/halo_props_place.py [--mode apply|remove]
"""
import json
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import halo_props_v2 as HP  # noqa: E402

PLAN = os.path.join(ROOT, "docs", "design", "halo_plan_v2_2026-10-11.json")
OUT = os.path.join(ROOT, "build", "wk", "halo_props_place.lua")
STAND = [("Lantern", "Halo_Lantern"), ("Planter", "Halo_Planter"), ("PotFlowers", "Halo_PotFlowers"),
         ("FlowerPotHQ", "Halo_PotFlowers"), ("RoundTree", "Halo_RoundTree"), ("Topiary", "Halo_Topiary"),
         ("Balustrade", "Halo_Balustrade"), ("Town_Halo_Fountain3", "Town_Halo_Fountain3")]


def kit_fits():
    fits = {}
    with open(HP.KIT_LIST, encoding="utf-8") as f:
        for ln in f:
            ln = ln.strip()
            if ln and not ln.startswith("#"):
                name, fit = ln.split()[:2]
                k, v = fit.split("=")
                fits[name] = (k, float(v))
    return fits


def box_size(p, fits):
    cat, r, h = HP.kit_cat(p["kit"])
    foot = max(0.8, r * 1.4)
    if p["kit"] in fits:
        k, v = fits[p["kit"]]
        if k == "h":
            return [foot, v, foot]
        return [v, h, max(1.0, v * 0.45)]
    if p["kit"] == "NEW_WallLamp":
        return [0.8, 1.5, 0.6]
    if p["kit"] == "NEW_SteppingStones":
        return [7, 0.5, 2]
    return [foot, h, foot]


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def build(mode):
    plan = json.load(open(PLAN, encoding="utf-8"))
    fits = kit_fits()
    rows = []
    for p in plan["dressing"]["props"]:
        stand = next((s for pre, s in STAND if pre in p["kit"]), None)
        target_h = None
        if stand and stand != "Town_Halo_Fountain3":
            target_h = fits.get(p["kit"], ("h", HP.kit_cat(p["kit"])[2]))[1] * p["scale"]
        size = [round(v * p["scale"], 2) for v in box_size(p, fits)]
        wall = 4.8 if p["kit"] == "NEW_WallLamp" else 0
        rows.append("{%s,%s,%s,%s,%d,%s,%s,%s,%s,%s,%s,%s,%s}" % (
            lua_str(p["id"]), lua_str(p["kit"]), p["at"][0], p["at"][1], p["yaw"], lua_str(stand or ""),
            round(target_h, 2) if target_h else 0, "{%s,%s,%s}" % tuple(size), "true" if p["kit"].startswith("NEW_") else "false",
            "true" if p.get("top") else "false", lua_str(p["why"]), lua_str(p["anchor"]), wall))
    code = TEMPLATE.replace("__MODE__", mode).replace("__ROWS__", ",\n".join(rows))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, "w", encoding="utf-8", newline="\n").write(code)
    return code


TEMPLATE = r'''-- generated by tools/worldkit/halo_props_place.py
local MODE = "__MODE__"
local R = {
__ROWS__
}
local halo = workspace:FindFirstChild("HaloV2")
if not halo then return "no Workspace.HaloV2" end
local old = halo:FindFirstChild("Props")
if old then old:Destroy() end
if MODE == "remove" then return "removed HaloV2.Props" end
local kit = game:GetService("ServerStorage"):FindFirstChild("WorldKit3D")
local root = Instance.new("Folder")
root.Name = "Props"
local fS = Instance.new("Folder"); fS.Name = "StandIn"; fS.Parent = root
local fP = Instance.new("Folder"); fP.Name = "Placeholder"; fP.Parent = root
local groundP = RaycastParams.new()
groundP.FilterType = Enum.RaycastFilterType.Include
groundP.FilterDescendantsInstances = { workspace.Terrain, halo:FindFirstChild("Ground") }
local topP = RaycastParams.new()
topP.FilterType = Enum.RaycastFilterType.Include
topP.FilterDescendantsInstances = { halo:FindFirstChild("Buildings") }
local function groundAt(x, z, top)
	local hit = workspace:Raycast(Vector3.new(x, 400, z), Vector3.new(0, -700, 0), top and topP or groundP)
	return hit and hit.Position.Y or nil
end
local nS, nP, nNew, miss = 0, 0, 0, {}
for _, r in R do
	local id, kname, x, z, yaw, stand, th, size, isNew, top, why, anchor, wall = table.unpack(r)
	local gy = groundAt(x, z, top)
	if not gy then
		table.insert(miss, id)
		gy = 0
	end
	local dir = Vector3.new(math.sin(math.rad(yaw)), 0, math.cos(math.rad(yaw)))
	local inst
	local src = stand ~= "" and kit and kit:FindFirstChild(stand)
	if src then
		local m = src:Clone()
		if th > 0 then
			local _, s = m:GetBoundingBox()
			pcall(function() m:ScaleTo(m:GetScale() * th / s.Y) end)
		end
		local base = CFrame.lookAt(Vector3.new(x, 0, z), Vector3.new(x, 0, z) + dir)
		m:PivotTo(base)
		local cf, s = m:GetBoundingBox()
		m:PivotTo(base + Vector3.new(0, gy - (cf.Position.Y - s.Y / 2), 0))
		for _, d in m:GetDescendants() do
			if d:IsA("BasePart") then d.Anchored = true; d.CanCollide = false end
		end
		m:SetAttribute("StandIn", stand)
		m.Name = id .. "_" .. kname
		m.Parent = fS
		inst = m
		nS += 1
	else
		local b = Instance.new("Part")
		b.Name = id .. "_" .. kname
		b.Size = Vector3.new(size[1], size[2], size[3])
		b.Anchored = true; b.CanCollide = false; b.CastShadow = false
		b.Material = Enum.Material.SmoothPlastic
		b.Transparency = 0.45
		b.Color = isNew and Color3.fromRGB(255, 150, 40) or Color3.fromRGB(90, 160, 255)
		local p0 = Vector3.new(x, gy + wall + size[2] / 2, z)
		b.CFrame = CFrame.lookAt(p0, p0 + dir)
		local bb = Instance.new("BillboardGui")
		bb.Size = UDim2.fromOffset(150, 30); bb.StudsOffset = Vector3.new(0, size[2] / 2 + 1.2, 0)
		bb.MaxDistance = 90; bb.AlwaysOnTop = false; bb.LightInfluence = 0
		local t = Instance.new("TextLabel")
		t.Size = UDim2.fromScale(1, 1); t.BackgroundTransparency = 1
		t.Text = id .. " " .. (kname:gsub("HaloReasonHQ_", ""):gsub("NEW_", "+"):gsub("HaloFlagpole_", "Flag"))
		t.TextScaled = true; t.Font = Enum.Font.GothamBold
		t.TextColor3 = isNew and Color3.fromRGB(255, 120, 0) or Color3.fromRGB(30, 90, 200)
		t.TextStrokeTransparency = 0.3; t.Parent = bb
		bb.Parent = b
		b:SetAttribute("Placeholder", true)
		b.Parent = fP
		inst = b
		nP += 1
		if isNew then nNew += 1 end
	end
	inst:SetAttribute("PropId", id); inst:SetAttribute("Kit", kname); inst:SetAttribute("Why", why); inst:SetAttribute("Anchor", anchor)
end
root.Parent = halo
return string.format("HaloV2.Props: stand-in %d, placeholder %d (NEW %d, made-not-imported %d), no ground %d %s",
	nS, nP, nNew, nP - nNew, #miss, table.concat(miss, ","))
'''


def main():
    mode = "apply"
    if "--mode" in sys.argv:
        mode = sys.argv[sys.argv.index("--mode") + 1]
    code = build(mode)
    jp = os.path.join(os.environ.get("TEMP", ROOT), "halo_props_place.json")
    json.dump({"code": code, "datamodel_type": "Edit"}, open(jp, "w", encoding="utf-8"), ensure_ascii=False)
    r = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "studio_mcp.py"), "call", "execute_luau", "@" + jp],
                       env=dict(os.environ, STUDIO_NAME="WorldKit"), capture_output=True, text=True, encoding="utf-8", cwd=ROOT)
    print(r.stdout.strip()[-800:] or r.stderr.strip()[-800:])


if __name__ == "__main__":
    main()
