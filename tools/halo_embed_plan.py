"""Embed docs/design/halo_layout_plan_2026-10-10.json into the Halo Citadel props tool as a plain table literal.

  py tools/halo_embed_plan.py [tools/worldkit/woods_terrain.luau tools/worldkit/woods_dress.luau]

Replaces everything between the lines `--@PLAN_BEGIN` and `--@PLAN_END` with `local PLAN = { ... }` (so the tools stay
standalone in Studio and run offline in the Luau CLI). Re-run after editing the plan json.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PLAN = ROOT / "docs/design/halo_layout_plan_2026-10-10.json"
DEFAULT = ["tools/worldkit/halo_props.luau"]


def lua(v, ind=0):
    pad = "\t" * ind
    if isinstance(v, dict):
        items = [f"{pad}\t{k if k.isidentifier() else '[%s]' % json.dumps(k)} = {lua(x, ind + 1)}," for k, x in v.items()
                 if not k.startswith("_")]
        return "{\n" + "\n".join(items) + f"\n{pad}}}"
    if isinstance(v, list):
        if all(isinstance(x, (int, float)) for x in v):
            return "{ " + ", ".join(repr(x) for x in v) + " }"
        return "{ " + ", ".join(lua(x, ind) for x in v) + " }"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return json.dumps(v, ensure_ascii=False)


def main():
    plan = json.loads(PLAN.read_text(encoding="utf-8"))
    block = "--@PLAN_BEGIN (generated by tools/halo_embed_plan.py from docs/design/halo_layout_plan_2026-10-10.json)\n" \
            f"local PLAN = {lua(plan)}\n--@PLAN_END"
    for rel in (sys.argv[1:] or DEFAULT):
        p = ROOT / rel
        if not p.exists():
            print("skip (missing)", rel)
            continue
        s = p.read_text(encoding="utf-8")
        a, b = s.find("--@PLAN_BEGIN"), s.find("--@PLAN_END")
        if a < 0 or b < 0:
            print("no markers in", rel)
            continue
        s = s[:a] + block + s[b + len("--@PLAN_END"):]
        p.write_text(s, encoding="utf-8")
        print("embedded into", rel)


if __name__ == "__main__":
    main()
